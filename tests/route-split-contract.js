const assert = require('assert')
const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '..')
const appJson = JSON.parse(fs.readFileSync(path.join(root, 'app.json'), 'utf8'))
const showQr = fs.readFileSync(path.join(root, 'pages/showqr/showqr.js'), 'utf8')
const cardCode = fs.readFileSync(path.join(root, 'pages/cardcode/cardcode.js'), 'utf8')
const permissionWxml = fs.readFileSync(path.join(root, 'pages/shareqr/shareqr.wxml'), 'utf8')
const cardWxmlPath = path.join(root, 'pages/cardshareqr/cardshareqr.wxml')

assert.ok(fs.existsSync(cardWxmlPath), 'Missing independent card visitor QR page.')
const cardWxml = fs.readFileSync(cardWxmlPath, 'utf8')
assert.ok(appJson.pages.indexOf('pages/cardshareqr/cardshareqr') !== -1)
assert.ok(showQr.indexOf("url: '/pages/shareqr/shareqr?val='") !== -1)
assert.ok(cardCode.indexOf("url: '/pages/cardshareqr/cardshareqr'") !== -1)
assert.ok(permissionWxml.indexOf('<timepicker') !== -1)
assert.ok(cardWxml.indexOf('bindchange="changeHour" min="0" max="23"') !== -1)
console.log('PASS: permission and card visitor QR pages are separated.')
